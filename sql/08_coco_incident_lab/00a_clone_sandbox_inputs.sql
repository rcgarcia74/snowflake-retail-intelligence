-- Engineer-owned setup phase for the isolated CoCo incident lab.
-- Run through the role-restricted retail_demo connection after 00_create_sandbox.sql.
-- This script creates only objects in RETAIL_DEMO_COCO_LAB. Openflow remains stopped.

USE WAREHOUSE RETAIL_DEMO_WH;
USE DATABASE RETAIL_DEMO_COCO_LAB;

CREATE SCHEMA RAW;
CREATE SCHEMA CONFIG;
CREATE SCHEMA ANALYTICS;
CREATE SCHEMA SERVING;
CREATE SCHEMA VALIDATION;

CREATE TABLE RAW.MERCHANT_PLAN CLONE RETAIL_DEMO.RAW.MERCHANT_PLAN;
CREATE TABLE RAW.STORE_SALES_EVENTS CLONE RETAIL_DEMO.RAW.STORE_SALES_EVENTS;
CREATE TABLE CONFIG.DEMO_SCENARIO CLONE RETAIL_DEMO.CONFIG.DEMO_SCENARIO;
CREATE TABLE CONFIG.DEMO_SCENARIO_ITEM CLONE RETAIL_DEMO.CONFIG.DEMO_SCENARIO_ITEM;

SELECT
  CURRENT_ROLE(),
  CURRENT_DATABASE(),
  (SELECT COUNT(*) FROM RAW.MERCHANT_PLAN) AS MERCHANT_PLAN_ROWS,
  (SELECT COUNT(*) FROM RAW.STORE_SALES_EVENTS) AS SALES_EVENT_ROWS;
