-- Create the smallest Dynamic Table path needed to demonstrate a business-date contract.
-- This script explicitly resumes the X-Small warehouse for initialization.

USE WAREHOUSE RETAIL_DEMO_WH;
USE DATABASE RETAIL_DEMO_COCO_LAB;

ALTER WAREHOUSE RETAIL_DEMO_WH RESUME IF SUSPENDED;

CREATE OR REPLACE DYNAMIC TABLE ANALYTICS.ITEM_STORE_DAY
  TARGET_LAG = DOWNSTREAM
  WAREHOUSE = RETAIL_DEMO_WH
  REFRESH_MODE = AUTO
  INITIALIZE = ON_CREATE
AS
SELECT
  TO_DATE(EVENT_TS) AS BUSINESS_DATE,
  STORE_SK,
  ITEM_SK,
  SUM(UNITS) AS UNITS,
  SUM(SALES_AMOUNT) AS SALES_AMOUNT,
  SUM(NET_PAID) AS NET_PAID
FROM RAW.STORE_SALES_EVENTS
GROUP BY TO_DATE(EVENT_TS), STORE_SK, ITEM_SK;

CREATE OR REPLACE DYNAMIC TABLE ANALYTICS.CATEGORY_STORE_DAY
  TARGET_LAG = '5 minutes'
  WAREHOUSE = RETAIL_DEMO_WH
  REFRESH_MODE = AUTO
  INITIALIZE = ON_CREATE
AS
SELECT
  d.BUSINESS_DATE,
  d.STORE_SK,
  i.CATEGORY,
  SUM(d.UNITS) AS UNITS,
  SUM(d.SALES_AMOUNT) AS SALES_AMOUNT,
  MAX(p.SALES_PLAN) AS SALES_PLAN,
  SUM(d.SALES_AMOUNT) - MAX(p.SALES_PLAN) AS SALES_TO_PLAN_VARIANCE
FROM ANALYTICS.ITEM_STORE_DAY d
JOIN CONFIG.DEMO_SCENARIO_ITEM i ON i.ITEM_SK = d.ITEM_SK
LEFT JOIN RAW.MERCHANT_PLAN p
  ON p.PLAN_DATE = d.BUSINESS_DATE
 AND p.STORE_SK = d.STORE_SK
 AND p.CATEGORY = i.CATEGORY
GROUP BY d.BUSINESS_DATE, d.STORE_SK, i.CATEGORY;

CREATE OR REPLACE SECURE VIEW SERVING.CATEGORY_SALES_TO_PLAN_TREND AS
SELECT
  BUSINESS_DATE,
  STORE_SK,
  CATEGORY,
  UNITS,
  SALES_AMOUNT,
  SALES_PLAN,
  SALES_TO_PLAN_VARIANCE,
  CASE
    WHEN SALES_TO_PLAN_VARIANCE IS NULL THEN NULL
    ELSE GREATEST(-SALES_TO_PLAN_VARIANCE, 0)
  END AS SALES_SHORTFALL
FROM ANALYTICS.CATEGORY_STORE_DAY;

CREATE OR REPLACE VIEW VALIDATION.BUSINESS_DATE_CONTRACT AS
WITH expected_plan AS (
  SELECT
    PLAN_DATE AS BUSINESS_DATE,
    STORE_SK,
    CATEGORY,
    MAX(SALES_PLAN) AS SOURCE_SALES_PLAN
  FROM RAW.MERCHANT_PLAN
  GROUP BY PLAN_DATE, STORE_SK, CATEGORY
), actual_trend AS (
  SELECT BUSINESS_DATE, STORE_SK, CATEGORY, SALES_PLAN
  FROM SERVING.CATEGORY_SALES_TO_PLAN_TREND
)
SELECT
  'source-plan-to-serving-date' AS CHECK_NAME,
  IFF(
    COUNT(*) = 175
    AND COUNT_IF(
      a.BUSINESS_DATE IS NULL
      OR a.SALES_PLAN IS NULL
      OR ABS(a.SALES_PLAN - e.SOURCE_SALES_PLAN) > 0.01
    ) = 0,
    'PASS',
    'FAIL'
  ) AS STATUS,
  COUNT(*) || ' expected plan rows; '
    || COUNT_IF(
      a.BUSINESS_DATE IS NULL
      OR a.SALES_PLAN IS NULL
      OR ABS(a.SALES_PLAN - e.SOURCE_SALES_PLAN) > 0.01
    ) || ' unmatched source-to-serving rows' AS DETAIL
FROM expected_plan e
LEFT JOIN actual_trend a
  ON a.BUSINESS_DATE = e.BUSINESS_DATE
 AND a.STORE_SK = e.STORE_SK
 AND a.CATEGORY = e.CATEGORY
UNION ALL
SELECT
  'source-plan-scenario-window',
  IFF(
    MIN(p.PLAN_DATE) >= DATEADD(DAY, -6, s.SIMULATION_DATE)
    AND MAX(p.PLAN_DATE) <= s.SIMULATION_DATE,
    'PASS',
    'FAIL'
  ),
  MIN(p.PLAN_DATE) || ' through ' || MAX(p.PLAN_DATE)
    || '; scenario date ' || s.SIMULATION_DATE
FROM RAW.MERCHANT_PLAN p
CROSS JOIN CONFIG.DEMO_SCENARIO s
GROUP BY s.SIMULATION_DATE;

CREATE OR REPLACE PROCEDURE VALIDATION.ASSERT_BUSINESS_DATE_CONTRACT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  NOT_READY EXCEPTION (-20011, 'BUSINESS_DATE_CONTRACT contains one or more failed checks');
  FAILURE_COUNT INTEGER;
BEGIN
  SELECT COUNT_IF(STATUS <> 'PASS') INTO :FAILURE_COUNT
  FROM VALIDATION.BUSINESS_DATE_CONTRACT;
  IF (FAILURE_COUNT > 0) THEN
    RAISE NOT_READY;
  END IF;
  RETURN 'PASS: source business dates reconcile to the serving trend';
END;
$$;

CREATE OR REPLACE PROCEDURE VALIDATION.ASSERT_EXPECTED_FAULT()
RETURNS VARCHAR
LANGUAGE SQL
EXECUTE AS OWNER
AS
$$
DECLARE
  INVALID_FAULT_STATE EXCEPTION (-20012, 'expected only the source-plan-to-serving-date check to fail');
  FAULT_COUNT INTEGER;
  UNEXPECTED_FAILURES INTEGER;
BEGIN
  SELECT COUNT_IF(CHECK_NAME = 'source-plan-to-serving-date' AND STATUS = 'FAIL')
    INTO :FAULT_COUNT
  FROM VALIDATION.BUSINESS_DATE_CONTRACT;
  SELECT COUNT_IF(CHECK_NAME <> 'source-plan-to-serving-date' AND STATUS <> 'PASS')
    INTO :UNEXPECTED_FAILURES
  FROM VALIDATION.BUSINESS_DATE_CONTRACT;
  IF (FAULT_COUNT <> 1 OR UNEXPECTED_FAILURES <> 0) THEN
    RAISE INVALID_FAULT_STATE;
  END IF;
  RETURN 'PASS: controlled source-to-serving business-date fault detected';
END;
$$;
